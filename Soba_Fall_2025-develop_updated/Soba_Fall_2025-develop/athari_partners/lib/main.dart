void main() async {
  WidgetsFlutterBinding.ensureInitialized();

  // Load environment variables
  try {
    await dotenv.load(fileName: ".env");
    if (authBypassEnabled) {
      debugPrint(
        'WARNING: BYPASS_AUTH=true — landing page and Firebase sign-in are '
        'skipped. Set BYPASS_AUTH=false in .env and restart.',
      );
    } else {
      debugPrint('Firebase auth enabled (BYPASS_AUTH=false).');
    }
  } catch (e) {
    print('Warning: Could not load .env file: $e');
  }

  // Initialize Firebase
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await configureFirestoreForPlatform();

  // Initialize OpenAI Service
  try {
    OpenAIService().initialize();
  } catch (e) {
    print('Warning: Could not initialize OpenAI Service: $e');
  }

  runApp(const MainApp());
}

/// Runs [ensureUserLinkedToCompany] once per auth session before the main app shell.
class _AuthCompanyGate extends StatefulWidget {
  const _AuthCompanyGate({super.key, required this.user});

  final User user;

  @override
  State<_AuthCompanyGate> createState() => _AuthCompanyGateState();
}

class _AuthCompanyGateState extends State<_AuthCompanyGate> {
  late Future<void> _linkFuture;

  @override
  void initState() {
    super.initState();
    _linkFuture = ensureUserLinkedToCompany(widget.user);
  }

  void _retryLink() {
    setState(() {
      _linkFuture = ensureUserLinkedToCompany(widget.user);
    });
  }

  @override
  Widget build(BuildContext context) {
    return FutureBuilder<void>(
      future: _linkFuture,
      builder: (context, linkSnap) {
        if (linkSnap.connectionState != ConnectionState.done) {
          return const Scaffold(
            body: Center(child: CircularProgressIndicator()),
          );
        }
        if (linkSnap.hasError) {
          return Scaffold(
            body: Center(
              child: Padding(
                padding: const EdgeInsets.all(24),
                child: Column(
                  mainAxisAlignment: MainAxisAlignment.center,
                  children: [
                    Text(
                      formatFirestoreSetupError(linkSnap.error!),
                      textAlign: TextAlign.center,
                    ),
                    const SizedBox(height: 20),
                    FilledButton(
                      onPressed: _retryLink,
                      child: const Text('Retry'),
                    ),
                    TextButton(
                      onPressed: () => FirebaseAuth.instance.signOut(),
                      child: const Text('Sign out'),
                    ),
                  ],
                ),
              ),
            ),
          );
        }
        return _AccountProfileGate(user: widget.user);
      },
    );
  }
}

/// Blocks [IndexScreen] until account onboarding is complete (new signups) or
/// a legacy workspace is detected (returning owners).
class _AccountProfileGate extends StatefulWidget {
  const _AccountProfileGate({super.key, required this.user});

  final User user;

  @override
  State<_AccountProfileGate> createState() => _AccountProfileGateState();
}

class _AccountProfileGateState extends State<_AccountProfileGate> {
  late Future<bool> _profileCheckFuture = _loadProfileFlag();
  bool _profileComplete = false;

  Future<bool> _loadProfileFlag() =>
      AccountProfileCompletion.isComplete(widget.user.uid);

  void _onProfileSaved() {
    setState(() {
      _profileComplete = true;
      _profileCheckFuture = _loadProfileFlag();
    });
  }

  @override
  Widget build(BuildContext context) {
    return FutureBuilder<bool>(
      future: _profileCheckFuture,
      builder: (context, snap) {
        if (_profileComplete) {
          return const IndexScreen(initialProcessStep: 0);
        }
        if (snap.connectionState != ConnectionState.done) {
          return const Scaffold(
            body: Center(child: CircularProgressIndicator()),
          );
        }
        if (snap.hasError) {
          return Scaffold(
            body: Center(
              child: Padding(
                padding: const EdgeInsets.all(24),
                child: Column(
                  mainAxisAlignment: MainAxisAlignment.center,
                  children: [
                    Text(
                      'Could not verify your profile.\n\n${snap.error}',
                      textAlign: TextAlign.center,
                    ),
                    const SizedBox(height: 20),
                    TextButton(
                      onPressed: () => FirebaseAuth.instance.signOut(),
                      child: const Text('Sign out'),
                    ),
                  ],
                ),
              ),
            ),
          );
        }
        if (_profileComplete || snap.data == true) {
          return const IndexScreen(initialProcessStep: 0);
        }
        return AccountProfilePage(
          user: widget.user,
          onCompleted: _onProfileSaved,
        );
      },
    );
  }
}

class MainApp extends StatelessWidget {
  const MainApp({super.key});

  @override
  Widget build(BuildContext context) {
    if (authBypassEnabled) {
      return MaterialApp(
        debugShowCheckedModeBanner: false,
        home: const IndexScreen(initialProcessStep: 0),
      );
    }

    return StreamBuilder<User?>(
      stream: FirebaseAuth.instance.authStateChanges(),
      builder: (context, snapshot) {
        // Reset the navigator when auth changes so pushed login/signup routes
        // cannot cover the post-sign-in shell (account profile → planning).
        final sessionKey = snapshot.data?.uid ?? 'signed-out';

        return MaterialApp(
          key: ValueKey<String>(sessionKey),
          debugShowCheckedModeBanner: false,
          home: _authHome(snapshot),
        );
      },
    );
  }

  Widget _authHome(AsyncSnapshot<User?> snapshot) {
    if (snapshot.connectionState == ConnectionState.waiting) {
      return const Scaffold(
        body: Center(child: CircularProgressIndicator()),
      );
    }

    final user = snapshot.data;
    if (user != null) {
      return _AuthCompanyGate(
        key: ValueKey<String>(user.uid),
        user: user,
      );
    }
    return const MyCatalystPlanLandingPage();
  }
}
